export interface BlockDefinition {
  id: string;
  name: string;
  icon?: string;
  type: "air" | "solid_wall" | "floor" | "machine" | "conduit" | "tunnel" | "farmland" | "crop";
  passable: boolean;
  occluding?: boolean;
  breakable?: boolean;
  drops?: Array<{ itemId: string; count: number; chance?: number }>;
  tillable?: boolean;
  tilledTileId?: string;
  tilledDrops?: Array<{ itemId: string; count: number; chance?: number }>;
  isCrop?: boolean;
  maxGrowthTicks?: number;
  growthStages?: number;
  stageTexturePrefix?: string;
  cropRenderStyle?: "crossed_quad" | "crop_grid" | "hemp";
  harvestDrops?: Array<{ itemId: string; count: number; chance?: number; min?: number; max?: number }>;
  textureDataUrl?: string;
}

function createBonsaiBlock(
  wood: string,
  name: string,
  icon: string,
  textureDataUrl: string
): BlockDefinition {
  return {
    id: `arcadialbonsaitrees:bonsai_${wood}_sapling`,
    name,
    icon,
    type: "crop",
    passable: true,
    breakable: true,
    isCrop: true,
    maxGrowthTicks: 1200,
    growthStages: 4,
    stageTexturePrefix: `arcadialbonsaitrees:bonsai_${wood}_stage_`,
    cropRenderStyle: "crossed_quad",
    drops: [{ itemId: `arcadialbonsaitrees:bonsai_${wood}_sapling`, count: 1 }],
    harvestDrops: [{ itemId: `arcadialbonsaitrees:bonsai_${wood}_cutting`, count: 4 }],
    tillable: false,
    textureDataUrl,
  };
}

