/**
 * Data-driven registry definitions for Items and Blocks.
 *
 * Backreferences & Verification:
 * - Scavenge Wall & Dirt loot drops: `config/scavenge/compactloot.json`
 *   https://github.com/kamunimaximus/CompactClaustrophobia/blob/master/config/scavenge/compactloot.json
 * - Scavenge Pickaxe drops: `config/scavenge/pickdrops.json`
 *   https://github.com/kamunimaximus/CompactClaustrophobia/blob/master/config/scavenge/pickdrops.json
 * - ContentTweaker custom items: `scripts/content.zs`
 *   https://github.com/kamunimaximus/CompactClaustrophobia/blob/master/scripts/content.zs
 * - Vanilla & Mod Wikis:
 *   - Farmland & Crops: https://minecraft.wiki/w/Farmland & https://minecraft.wiki/w/Wheat_Seeds
 *   - Bonsai Trees: https://ftbwiki.org/Bonsai_Trees
 *   - Compact Machines 3: https://ftbwiki.org/Compact_Machines_3
 */
export interface ItemDefinition {
  id: string;
  name: string;
  maxStackSize?: number;
  placeable?: boolean;
  placesTileId?: string;
  icon?: string;
  textureDataUrl?: string;
  isTool?: boolean;
  canTill?: boolean;
  plantable?: boolean;
  plantableOn?: string[];
  placesCropId?: string;
  edible?: boolean;
  alwaysEdible?: boolean;
  hungerRestore?: number;
  traits?: string[];
  crucibleMeltMb?: number;
  burnTimeTicks?: number;
  smeltsInto?: string;
}

function createBonsaiCuttingItem(
  wood: string,
  name: string,
  textureDataUrl: string
): ItemDefinition {
  return {
    id: `arcadialbonsaitrees:bonsai_${wood}_cutting`,
    name,
    maxStackSize: 64,
    icon: "🌿",
    traits: ["bonsai_cutting", "foliage"],
    crucibleMeltMb: 250,
    textureDataUrl,
  };
}

function createBonsaiSaplingItem(
  wood: string,
  name: string,
  icon: string,
  textureDataUrl: string
): ItemDefinition {
  const id = `arcadialbonsaitrees:bonsai_${wood}_sapling`;
  return {
    id,
    name,
    maxStackSize: 64,
    placeable: true,
    plantable: true,
    plantableOn: ["minecraft:farmland", "minecraft:dirt"],
    placesTileId: id,
    placesCropId: id,
    icon,
    traits: ["bonsai_sapling"],
    crucibleMeltMb: 250,
    textureDataUrl,
  };
}

