#!/usr/bin/env node
/**
 * Stage 2: Reads extracted PNG files from `assets/textures/` and generates
 * `src/render/textures.ts` with base64 data URLs.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { TEXTURE_MANIFEST, getAllTextureEntries } from "./texture-manifest.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT_DIR = path.resolve(__dirname, "..");
const EXTRACTED_TEXTURES_DIR = path.join(ROOT_DIR, "assets", "textures");
const OUTPUT_FILE = path.join(ROOT_DIR, "src", "render", "textures.ts");

export function buildTexturesTs() {
  const entries = getAllTextureEntries();

  const readPngAsDataUrl = (extractedRelPath) => {
    const filePath = path.join(EXTRACTED_TEXTURES_DIR, extractedRelPath);
    if (!fs.existsSync(filePath)) {
      throw new Error(
        `Missing extracted texture file: ${path.relative(ROOT_DIR, filePath)}. Run \`npm run extract-textures\` first.`
      );
    }
    const buf = fs.readFileSync(filePath);
    return `data:image/png;base64,${buf.toString("base64")}`;
  };

  const lines = [
    "/**",
    " * AUTO-GENERATED by `scripts/build-textures.mjs` from `assets/textures/` PNGs",
    " * (extracted from `vendor/compact-claustrophobia/` jars by `scripts/extract-textures.mjs`).",
    " * Run `npm run extract-assets` to re-extract from jars and rebuild this file.",
    " */",
    "",
  ];

  for (const item of TEXTURE_MANIFEST) {
    const rel = item.asset.replace(/^assets\//, "");
    const dataUrl = readPngAsDataUrl(rel);
    lines.push(`export const ${item.constName} =`);
    lines.push(`  "${dataUrl}";`);
  }

  lines.push("");
  lines.push("export const TEXTURE_MAP: Record<string, string> = {");
  for (const entry of entries) {
    if (entry.constName) {
      lines.push(`  "${entry.mapId}": ${entry.constName},`);
    } else {
      const dataUrl = readPngAsDataUrl(entry.extractedRelPath);
      lines.push(`  "${entry.mapId}": "${dataUrl}",`);
    }
  }
  lines.push("};");
  lines.push("");

  fs.writeFileSync(OUTPUT_FILE, lines.join("\n"), "utf8");
  console.log(
    `[Stage 2] Built ${path.relative(ROOT_DIR, OUTPUT_FILE)} with ${entries.length} base64 textures from ${path.relative(ROOT_DIR, EXTRACTED_TEXTURES_DIR)}`
  );
  return entries.length;
}

if (import.meta.url === `file:///${process.argv[1].replace(/\\/g, "/")}` || process.argv[1]?.endsWith("build-textures.mjs")) {
  buildTexturesTs();
}
